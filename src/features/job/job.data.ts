export const loadJobs = (): JobRecord[] => {
  try {
    const raw = localStorage.getItem(JOB_STORAGE_KEY);
    if (raw) return JSON.parse(raw) as JobRecord[];
  } catch {}
  return initialMockJobs;
};

export const saveJobs = (jobs: JobRecord[]): void => {
  try {
    localStorage.setItem(JOB_STORAGE_KEY, JSON.stringify(jobs));
  } catch {}
};
